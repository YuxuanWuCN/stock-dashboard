def count_placeholders() -> Dict[str, int]:
    """统计各内容区块中剩余的占位符数量（spec FR-022）。

    Returns:
        区块名 -> 占位符出现次数。总数为 0 时表示所有真实事实已补齐。
    """
    counts: Dict[str, int] = {}

    def _count_in(obj) -> int:
        """递归统计任意嵌套结构中 PH 出现的次数。"""
        if isinstance(obj, str):
            return obj.count(PH)
        if isinstance(obj, dict):
            return sum(_count_in(v) for v in obj.values())
        if isinstance(obj, (list, tuple)):
            return sum(_count_in(v) for v in obj)
        return 0

    counts["团队成员"] = _count_in(TEAM)
    counts["指导教师"] = _count_in(ADVISORS)
    counts["个人成长叙事"] = _count_in(GROWTH_ACTS)
    counts["产业调研"] = _count_in(INDUSTRY_RESEARCH)
    counts["达观对接记录"] = _count_in(DAGUAN_ENGAGEMENT)
    return counts
